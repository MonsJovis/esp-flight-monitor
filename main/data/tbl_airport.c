/* German city-name lookup, keyed on the 4-letter ICAO airport code.
 *
 * The routeset API returns ICAO codes in `airport_codes` ("LOWW-EGLL") and
 * English city names in `location` ("Vienna"). This table supplies the German
 * exonym where Austrian usage genuinely has one (Mailand, Prag, Warschau,
 * Krakau, Klausenburg) and otherwise deliberately keeps the local spelling
 * (Amsterdam, Madrid, Barcelona) rather than inventing a German name nobody
 * uses. Sorted ascending by ICAO code for bsearch -- test_tables.c checks
 * sortedness and uniqueness directly against tbl_airport_entries().
 *
 * WHY IT IS THIS BIG. view_build.c's resolve_city() falls back to the API's
 * own `location` string when a code is missing here, and that fallback is not
 * merely English -- it is unvetted third-party data entry. LGRP came back as
 * "Rodes Island" and was rendered at him in 76 px type as the answer to "where
 * is that plane going". The table is therefore sized to make the fallback rare
 * across both places the device lives (AGENTS.md §6):
 *
 *   Gloggnitz  -- under the Vienna TMA and on the corridors between northern/
 *                 western Europe and the eastern Mediterranean, the Middle East
 *                 and Asia: European scheduled airports of any size, the Gulf,
 *                 Turkey, Israel, Egypt, North Africa, plus the Asian and North
 *                 American ends of the long-haul that crosses overhead.
 *   Pattaya    -- the Thai domestic network (VTBU U-Tapao is the field he will
 *                 actually be near), Southeast Asia, China, Japan, Korea, India
 *                 and the Australian gateways.
 *
 * RULES FOR ADDING A ROW.
 *
 *   1. The value is a CITY, not an airport. Every ICAO code of a city maps to
 *      the same string -- EGLL, EGKK, EGSS, EGGW and EGLC are all "London".
 *      He wants to know the city, not which runway.
 *   2. German exonym only where current Austrian usage genuinely has one
 *      (Mailand, Warschau, Krakau, Danzig, Breslau, Kopenhagen, Peking, Tokio,
 *      Kairo, Neu-Delhi, Kalkutta, Singapur). Current, not historical: Mumbai,
 *      not Bombay. Where in doubt, keep the local spelling -- an invented
 *      German name ("Neu-York") is worse than an honest foreign one.
 *   3. Latin-1 only. These strings reach the hero, and the three hero faces
 *      carry ASCII + U+00C0-U+00FF only (tools/build_fonts.sh CORE_RANGES).
 *      A Latin Extended-A character renders as NOTHING at 100 px, so Polish and
 *      Romanian names use a spelling that avoids it (Rzeszow keeps its o-acute,
 *      Wroclaw becomes Breslau, Timisoara drops its comma-below).
 *   4. Short. VIEW_HERO_LEN is 48 bytes and the shrink ladder punishes long
 *      names early (DESIGN.md §3), so nothing here exceeds 24 bytes.
 *   5. Verify the code. A wrong ICAO code is worse than a missing one: the
 *      missing one falls back, the wrong one confidently shows the wrong city.
 */
