#define AIRLINE_COUNT (sizeof(AIRLINES) / sizeof(AIRLINES[0]))

static int airline_cmp(const void *key, const void *elem)
{
    const char *k = (const char *)key;
    const str_lookup_t *e = (const str_lookup_t *)elem;
    return strcmp(k, e->key);
}

const char *airline_de(const char *icao3)
{
    if (icao3 == NULL || icao3[0] == '\0') {
        return NULL;
    }
    const str_lookup_t *hit = (const str_lookup_t *)bsearch(
        icao3, AIRLINES, AIRLINE_COUNT, sizeof(AIRLINES[0]), airline_cmp);
    return hit ? hit->value : NULL;
}

const str_lookup_t *tbl_airline_entries(size_t *count)
{
    *count = AIRLINE_COUNT;
    return AIRLINES;
}
